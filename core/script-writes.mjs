/**
 * 파일 내용을 스크립트로 쓰려 하는가 — **판정만.** (D6)
 *
 * ## 왜 막는가 — 조용히 실패하는 도구를 쓰지 못하게
 *
 * 스크립트로 파일을 고치면 실패가 두 종류로 온다. 둘 다 조용하다.
 *
 *   ① **이스케이프를 세 번 해석한다.** 셸 → 스크립트 문자열 → 대상 언어.
 *      세 파서를 머릿속으로 돌려 맞혀야 하고, 틀리면 `\n` 이 실제 줄바꿈이 되어
 *      대상 파일이 문법 오류로 죽는다.
 *   ② **못 찾아도 성공이라고 한다.** `str.replace(old, new)` 는 `old` 가 없으면
 *      원본을 그대로 돌려주고 끝난다. 오류가 없다. 편집이 안 됐는데 됐다고 믿는다.
 *
 * ②를 하네스 말로 하면 **`cannot` 을 `pass` 로 접는 것**이다. Edit 도구는
 * 못 찾으면 거부한다. 그러니 스크립트로 파일을 고치는 순간, 하네스가 코드에서
 * 없앤 실패를 에이전트가 제 손으로 다시 들여온다.
 *
 * 이 규칙은 `AGENTS.md` 에 적혀 있었고 지뢰표에도 있었다. 그런데 한 세션에서
 * 세 번 어겼다 — **문서에 적힌 금지는 스스로 집행하지 않는다.** 그래서 게이트다.
 *
 * ## 무엇을 막고 무엇을 통과시키나 — 좁게
 *
 * 스크립트는 **읽기·측정에 정당하게** 쓰인다. 그리고 heredoc 은 커밋 메시지에도
 * 쓰인다. 넓게 막으면 커밋이 전부 막히고, 그러면 사람이 게이트를 끈다.
 *
 *   막는다   python 이 실행 파일인 조각이 있고 + 쓰기 표지가 있다
 *            (`open(…, 'w'|'a'|'x')` · `mode='w'` · `.write_text(` · `.write_bytes(`)
 *   통과     python 읽기·측정 · `git commit -F - <<'EOF'` · `node -e` 측정
 *
 * **실행 파일은 어댑터가 알려 준다**(heredoc 본문을 뺀 조각의 첫 토큰). 그래야
 * 커밋 메시지가 `open(p, 'w')` 를 **논할** 때 걸리지 않는다 — 이 결정의 커밋
 * 메시지가 바로 그렇다.
 *
 * ## 범위 밖으로 둔 것
 *
 * `sed -i` · `perl -pi` 도 ②와 같은 실패를 한다(못 찾으면 조용히 안 바꾼다).
 * 하지만 흔하게 쓰이고, 실제로 어긴 것은 python 이었다. 거짓 차단을 먼저 재지
 * 않고 넓히지 않는다 — 넓힐 근거가 생기면 `D6` 의 뒤집힐 조건을 따라 다시 잰다.
 */
import { skip, block } from './verdict.mjs';

const PYTHON = /^(python3?(\.\d+)?|py)$/;

const WRITE = [
  // 모드는 **두 번째 인자**다 — 쉼표 뒤로 좁힌다. 안 그러면 `open('a')` 처럼
  // 파일 이름이 한 글자일 때 그 이름을 모드로 읽고 **읽기를 막는다.**
  /\bopen\s*\([^)]*?,\s*['"][wax][bt+]*['"]/,  // open(p, 'w') · io.open(p, "a", …)
  /\bmode\s*=\s*['"][wax]/,                      // open(p, mode='w')
  /\.write_(text|bytes)\s*\(/,                   // Path(...).write_text(...)
];

/**
 * @param {{ heads: string[], command: string }} arg
 *   heads   조각별 실행 파일 이름 (heredoc 본문을 뺀 것 — 어댑터가 준다)
 *   command 명령 전체 (heredoc 본문 포함 — 스크립트 내용은 거기 있다)
 */
export function checkScriptWrite({ heads, command }) {
  if (!heads.some((h) => PYTHON.test(h))) return skip('python 을 실행하지 않는다');

  const hit = WRITE.find((re) => re.test(command));
  if (!hit) return skip('python 이 읽기·측정만 한다');

  return block(
    '파일 내용을 python 으로 쓰려 한다. **Write/Edit 도구로 써라.**\n\n' +
    '이유 둘 — 둘 다 조용한 실패다:\n' +
    '  ① 이스케이프가 셸·python·대상 언어에서 세 번 해석된다. `\\n` 이 실제\n' +
    '     줄바꿈이 되어 대상 파일이 문법 오류로 죽는다\n' +
    '  ② `str.replace` 는 못 찾아도 원본을 그대로 돌려준다. 편집이 안 됐는데\n' +
    '     됐다고 믿게 된다. Edit 도구는 못 찾으면 **거부한다**\n\n' +
    `(걸린 표지: ${hit.source})\n\n` +
    'python 으로 **읽거나 재는 것**은 막지 않는다. 쓰는 부분만 도구로 옮겨라. (D6)'
  );
}
